function transportLine(
  source: string,
  id: string,
  classes: string[],
  color: string,
  width: number,
  minzoom: number,
  dash?: number[],
): LineLayerSpecification {
  return {
    id,
    type: "line",
    source,
    "source-layer": "transportation",
    minzoom,
    filter: ["match", ["get", "class"], classes, true, false],
    layout: { "line-cap": "round", "line-join": "round" },
    paint: {
      "line-color": color,
      ...(dash ? { "line-dasharray": dash } : {}),
      "line-width": [
        "interpolate",
        ["exponential", 1.2],
        ["zoom"],
        8,
        width * 0.2,
        12,
        width,
        16,
        width * 2,
        20,
        width * 4,
      ],
      "line-opacity": ["case", ["==", ["get", "brunnel"], "tunnel"], 0.45, 1],
    },
  };
}

/** Outdoor is a presentation choice, never a source of recorded elevations. */
export function createOutdoorStyle(
  locale: string,
  variant: "outdoor" | "dark" = "outdoor",
): StyleSpecification {
  const source = variant;
  const palette = palettes[variant];
  const font = ["Noto Sans Regular"];
  const name: ExpressionSpecification = [
    "coalesce",
    ["get", `name:${locale}`],
    ["get", "name"],
    ["get", "name:latin"],
    "",
  ];
  const labelPaint: SymbolLayerSpecification["paint"] = {
    "text-color": palette.label,
    "text-halo-color": palette.halo,
    "text-halo-width": 1.5,
  };
  return {
    version: 8,
    name: variant === "dark" ? "Track Atlas Dark" : "Track Atlas Outdoor",
    glyphs: "https://tiles.openfreemap.org/fonts/{fontstack}/{range}.pbf",
    sources: {
      [source]: { type: "vector", url: "https://tiles.openfreemap.org/planet" },
    },
    layers: [
      {
        id: `${source}-background`,
        type: "background",
        paint: { "background-color": palette.background },
      },
      {
        id: `${source}-landuse`,
        type: "fill",
        source,
        "source-layer": "landuse",
        paint: {
          "fill-color": [
            "match",
            ["get", "class"],
            ["residential", "commercial", "industrial"],
            palette.urban,
            ["farmland", "farm", "orchard", "vineyard"],
            palette.farmland,
            palette.land,
          ],
          "fill-opacity": 0.7,
        },
      },
      {
        id: `${source}-parks`,
        type: "fill",
        source,
        "source-layer": "park",
        paint: { "fill-color": palette.park, "fill-opacity": 0.5 },
      },
      {
        id: `${source}-landcover`,
        type: "fill",
        source,
        "source-layer": "landcover",
        paint: {
          "fill-color": [
            "match",
            ["get", "class"],
            "wood",
            palette.wood,
            "grass",
            palette.grass,
            "wetland",
            palette.wetland,
            "ice",
            palette.ice,
            "sand",
            palette.sand,
            palette.otherLandcover,
          ],
        },
      },
      {
        id: `${source}-park-boundaries`,
        type: "line",
        source,
        "source-layer": "park",
        minzoom: 8,
        paint: {
          "line-color": palette.boundary,
          "line-width": 1,
          "line-dasharray": [4, 3],
          "line-opacity": 0.7,
        },
      },
      {
        id: `${source}-water`,
        type: "fill",
        source,
        "source-layer": "water",
        filter: ["!=", ["get", "brunnel"], "tunnel"],
        paint: { "fill-color": palette.water },
      },
      {
        id: `${source}-waterways`,
        type: "line",
        source,
        "source-layer": "waterway",
        minzoom: 8,
        paint: {
          "line-color": palette.waterway,
          "line-width": ["interpolate", ["linear"], ["zoom"], 8, 0.5, 16, 2],
        },
      },
      {
        id: `${source}-buildings`,
        type: "fill",
        source,
        "source-layer": "building",
        minzoom: 15,
        paint: { "fill-color": palette.building, "fill-opacity": 0.65 },
      },
      transportLine(
        source,
        `${source}-major-roads`,
        ["motorway", "trunk", "primary"],
        palette.majorRoad,
        1.6,
        5,
      ),
      transportLine(
        source,
        `${source}-secondary-roads`,
        ["secondary", "tertiary"],
        palette.secondaryRoad,
        1.2,
        8,
      ),
      transportLine(
        source,
        `${source}-minor-roads`,
        ["minor", "service", "pedestrian"],
        palette.minorRoad,
        0.8,
        12,
      ),
      transportLine(
        source,
        `${source}-track-casing`,
        ["track"],
        palette.halo,
        2.4,
        11,
      ),
      transportLine(
        source,
        `${source}-tracks`,
        ["track"],
        palette.track,
        1.3,
        11,
        [4, 1.5],
      ),
      transportLine(
        source,
        `${source}-path-casing`,
        ["path"],
        palette.halo,
        2,
        11,
      ),
      transportLine(
        source,
        `${source}-paths`,
        ["path"],
        palette.path,
        1.1,
        11,
        [1.5, 1.5],
      ),
      // Text-only outdoor labels avoid a remote sprite/icon dependency. Do not
      // infer access rights, hiking-route membership or difficulty from linework.
      {
        id: `${source}-peaks`,
        type: "symbol",
        source,
        "source-layer": "mountain_peak",
        minzoom: 10,
        layout: {
          "text-field": [
            "case",
            ["all", ["has", "ele"], ["!=", ["get", "ele"], null]],
            ["concat", name, "\n", ["to-string", ["get", "ele"]], " m"],
            name,
          ],
          "text-font": font,
          "text-size": 12,
          "text-max-width": 9,
        },
        paint: { ...labelPaint, "text-color": palette.peakLabel },
      },
      {
        id: `${source}-park-names`,
        type: "symbol",
        source,
        "source-layer": "park",
        minzoom: 10,
        layout: {
          "text-field": name,
          "text-font": font,
          "text-size": 12,
          "text-max-width": 12,
        },
        paint: { ...labelPaint, "text-color": palette.parkLabel },
      },
      {
        id: `${source}-places`,
        type: "symbol",
        source,
        "source-layer": "place",
        minzoom: 4,
        filter: [
          "match",
          ["get", "class"],
          ["city", "town", "village", "hamlet", "suburb", "isolated_dwelling"],
          true,
          false,
        ],
        layout: {
          "text-field": name,
          "text-font": font,
          "text-size": ["interpolate", ["linear"], ["zoom"], 4, 11, 14, 15],
          "symbol-sort-key": ["coalesce", ["get", "rank"], 100],
        },
        paint: labelPaint,
      },
      {
        id: `${source}-pois`,
        type: "symbol",
        source,
        "source-layer": "poi",
        minzoom: 13,
        filter: [
          "match",
          ["get", "subclass"],
          [
            "alpine_hut",
            "wilderness_hut",
            "shelter",
            "drinking_water",
            "spring",
            "camp_site",
            "viewpoint",
            "picnic_site",
          ],
          true,
          false,
        ],
        layout: {
          "text-field": name,
          "text-font": font,
          "text-size": 11,
          "text-max-width": 10,
        },
        paint: labelPaint,
      },
      {
        id: `${source}-path-names`,
        type: "symbol",
        source,
        "source-layer": "transportation_name",
        minzoom: 13,
        filter: ["match", ["get", "class"], ["path", "track"], true, false],
        layout: {
          "symbol-placement": "line",
          "symbol-spacing": 300,
          "text-field": name,
          "text-font": font,
          "text-size": 12,
        },
        paint: { ...labelPaint, "text-color": palette.pathLabel },
      },
      {
        id: `${source}-road-names`,
        type: "symbol",
        source,
        "source-layer": "transportation_name",
        minzoom: 14,
        filter: [
          "match",
          ["get", "class"],
          ["minor", "primary", "secondary", "tertiary", "service"],
          true,
          false,
        ],
        layout: {
          "symbol-placement": "line",
          "symbol-spacing": 500,
          "text-field": name,
          "text-font": font,
          "text-size": 10,
        },
        paint: { ...labelPaint, "text-color": palette.roadLabel },
      },
      {
        id: `${source}-water-names`,
        type: "symbol",
        source,
        "source-layer": "water_name",
        minzoom: 10,
        layout: { "text-field": name, "text-font": font, "text-size": 12 },
        paint: { ...labelPaint, "text-color": palette.waterLabel },
      },
    ],
  };
}
